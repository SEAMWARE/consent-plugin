package consent

import "regexp"

// uuidPattern matches a canonical, hyphenated UUID of any version, either case.
const uuidPattern = `^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`

var uuidRegexp = regexp.MustCompile(uuidPattern)

// IsUUID reports whether s is a canonical hyphenated UUID. Values that end up
// in a URL path or a privacyNoticeId query must pass it first.
func IsUUID(s string) bool {
	return uuidRegexp.MatchString(s)
}
